// Bloques: asistente por pasos (<tsl-wizard> y alta de un espacio), panel de control, autenticación y ajustes.
const { chromium } = require('playwright');
const base = process.env.BASE_URL || 'http://localhost:24100';
let fails = 0;
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 950 } });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push(String(e)));
  await p.goto(`${base}/components.html`); await p.waitForLoadState('networkidle');
  const show = async (id) => { await p.evaluate(i => document.getElementById(i).scrollIntoView({ block: 'start' }), id); await p.waitForTimeout(200); };
  const active = () => p.evaluate(() => { const a = document.activeElement; return a ? (a.id || a.name || a.textContent.trim().slice(0, 30)) : ''; });
  const toasts = () => p.evaluate(() => [...document.querySelectorAll('.tsl-toast')].map(t => t.textContent.replace(/\s+/g, ' ').trim()).join(' | '));

  // ---- <tsl-wizard> ----
  await show('wizard');
  const wz = p.locator('#demo-wizard');
  const jumps = wz.locator('.tsl-wizard__jump');
  const state = () => wz.evaluate(e => ({ i: e.index, vis: [...e.querySelectorAll('.tsl-wizard__step')].filter(s => !s.hidden).length, btn: ['prev', 'next', 'submit'].map(k => e.querySelector(`[data-${k}]`).hidden ? 'x' : 'o').join(''), cur: [...e.querySelectorAll('.tsl-wizard__jump')].map(j => (j.getAttribute('aria-current') ? 'C' : j.disabled ? 'd' : 'o')).join('') }));
  let st = await state();
  ok(await jumps.count() === 3 && (await jumps.allTextContents()).join() === 'Cuenta,Perfil,Confirmar', 'el indicador se genera con el data-title de cada paso');
  ok(st.i === 0 && st.vis === 1 && st.btn === 'xox' && st.cur === 'Cod', `inicio: un solo paso visible, sin «Atrás» ni «Crear», pasos futuros no pulsables (${st.cur})`);
  const gap = await wz.evaluate(e => { const l = e.querySelector('.tsl-wizard__step:not([hidden]) > legend').getBoundingClientRect(); const n = e.querySelector('.tsl-wizard__step:not([hidden]) > legend + *').getBoundingClientRect(); return n.top - l.bottom; });
  ok(gap >= 10, `el título del paso respira respecto al primer campo (${Math.round(gap)} px)`);
  await p.evaluate(() => { window.__steps = []; document.querySelector('#demo-wizard').addEventListener('tsl-step', e => window.__steps.push(e.detail)); });
  await wz.locator('[data-next]').click();
  ok((await state()).i === 0 && await wz.locator('[name=correo]').getAttribute('aria-invalid') === 'true' && await active() === 'correo', 'con el campo obligatorio vacío no avanza: lo marca inválido y lo enfoca');
  await wz.locator('[name=correo]').fill('no-es-correo');
  await wz.locator('[name=correo]').press('Enter');
  ok((await state()).i === 0, 'un correo mal escrito tampoco deja avanzar');
  await wz.locator('[name=correo]').fill('ana@acme.example');
  ok(await wz.locator('[name=correo]').getAttribute('aria-invalid') === null, 'al corregirlo se quita la marca de error');
  await wz.locator('[name=correo]').press('Enter');
  st = await state();
  ok(st.i === 1 && st.btn === 'oox' && await active() === 'Tu perfil', 'Enter en un campo avanza y el foco va al título del paso');
  ok(JSON.stringify(await p.evaluate(() => window.__steps)) === JSON.stringify([{ index: 1, count: 3, title: 'Perfil' }]), 'tsl-step informa índice, total y título');
  await wz.locator('[name=nombre]').fill('Ana');
  await wz.locator('[data-next]').click();
  ok((await state()).i === 1 && await wz.locator('tsl-select[name=rol]').getAttribute('aria-invalid') === 'true', 'también valida los tsl-select obligatorios');
  await wz.locator('tsl-select[name=rol] .tsl-trigger').click();
  await wz.locator('tsl-select[name=rol] .tsl-select__option', { hasText: 'Diseño' }).click();
  await wz.locator('[data-next]').click();
  st = await state();
  ok(st.i === 2 && st.btn === 'oxo' && st.cur === 'ooC', `último paso: «Atrás» y «Crear», y los anteriores se pueden pulsar (${st.cur})`);
  await p.evaluate(() => { window.__sub = null; document.querySelector('#demo-wizard').addEventListener('tsl-submit', e => (window.__sub = e.detail.values)); });
  await wz.locator('[data-submit]').click();
  ok((await state()).i === 2 && await p.evaluate(() => window.__sub) === null, 'sin aceptar las condiciones no se envía');
  await jumps.nth(0).click();
  ok((await state()).i === 0 && (await state()).cur === 'Coo', 'pulsar un paso visitado vuelve a él; los demás siguen disponibles');
  await jumps.nth(2).click();
  ok((await state()).i === 2, 'y se puede volver directo al último visitado');
  await wz.locator('[name=terminos]').check();
  await wz.locator('[data-submit]').click();
  ok(JSON.stringify(await p.evaluate(() => window.__sub)) === JSON.stringify({ correo: 'ana@acme.example', nombre: 'Ana', rol: 'dis', terminos: 'si' }), 'al terminar emite tsl-submit con todos los valores');
  // Un paso anterior que deja de ser válido: al enviar se vuelve a él
  await jumps.nth(0).click();
  await wz.locator('[name=correo]').fill('');
  await jumps.nth(2).click();
  ok((await state()).i === 0, 'no deja saltar adelante si un paso anterior quedó inválido');
  await wz.locator('[name=correo]').fill('ana@acme.example');
  await jumps.nth(2).click();
  await wz.evaluate(e => { e.querySelector('[name=correo]').value = ''; });
  await wz.locator('[data-submit]').click();
  ok((await state()).i === 0 && await active() === 'correo', 'al enviar, si un paso tiene errores lleva a ese paso y a su campo');
  await wz.evaluate(e => e.querySelector('form').reset());
  await p.waitForTimeout(50);
  st = await state();
  ok(st.i === 0 && st.cur === 'Cod', 'form.reset() vuelve al primer paso y olvida el avance');

  // ---- Alta de un espacio ----
  await show('pattern-wizard');
  const alta = p.locator('#alta-wizard');
  await alta.locator('#alta-nombre').fill('Acme Diseño Ñandú');
  ok(await alta.locator('#alta-slug').inputValue() === 'acme-diseno-nandu', 'la dirección se propone desde el nombre (sin acentos ni espacios)');
  await alta.locator('#alta-slug').fill('Mal Nombre');
  await alta.locator('tsl-select[name=region] .tsl-trigger').click();
  await alta.locator('tsl-select[name=region] .tsl-select__option', { hasText: 'Unión Europea' }).click();
  await alta.locator('[data-next]').click();
  ok(await alta.evaluate(e => e.index) === 0 && await alta.locator('#alta-slug').getAttribute('aria-invalid') === 'true', 'una dirección con mayúsculas o espacios no pasa el pattern');
  await alta.locator('#alta-nombre').fill('Acme Diseño');
  ok(await alta.locator('#alta-slug').inputValue() === 'Mal Nombre', 'si la persona editó la dirección, el nombre ya no la sobrescribe');
  await alta.locator('#alta-slug').fill('acme-diseno');
  await alta.locator('[data-next]').click();
  ok(await alta.evaluate(e => e.index) === 1, 'con datos válidos pasa a «Equipo»');
  const tagInput = alta.locator('#alta-invitados .tsl-tags__input');
  await tagInput.fill('ana@acme.example'); await tagInput.press('Enter');
  ok(await alta.evaluate(e => e.index) === 1, 'Enter en el campo de correos añade la etiqueta sin avanzar de paso');
  await tagInput.fill('no-es-correo'); await tagInput.press('Enter');
  ok(await alta.locator('#alta-invitados .tsl-chip').count() === 1 && (await alta.locator('#alta-invitados-err').textContent()).includes('no-es-correo'), 'un correo inválido se descarta con un aviso');
  await tagInput.fill('luis@acme.example'); await tagInput.press('Enter');
  await alta.locator('#alta-rol').selectOption('Administración');
  await alta.locator('[data-next]').click();
  await alta.locator('[data-next]').click();
  ok(await alta.evaluate(e => e.index) === 2, 'el plan es obligatorio');
  await alta.locator('input[name=plan][value=Equipo]').check({ force: true });
  await alta.locator('input[name=anual]').check({ force: true });
  await alta.locator('[data-next]').click();
  const resumen = (await alta.locator('#alta-resumen').textContent()).replace(/\s+/g, ' ');
  ok(resumen.includes('Acme Diseño') && resumen.includes('https://acme-diseno.tesela.app') && resumen.includes('Unión Europea') && resumen.includes('2 como Administración') && resumen.includes('Equipo, facturación anual'), `la revisión resume todo: ${resumen}`);
  await alta.locator('[data-submit]').click();
  ok(await alta.isVisible() && await alta.evaluate(e => e.index) === 3, 'sin aceptar las condiciones no se crea');
  await alta.locator('input[name=condiciones]').check();
  await alta.locator('[data-submit]').click();
  ok(await alta.isHidden() && await p.locator('#alta-hecho').isVisible() && (await p.locator('#alta-hecho-desc').textContent()).includes('https://acme-diseno.tesela.app') && await active() === 'Tu espacio está listo', 'al crear, la confirmación sustituye al formulario y recibe el foco');
  await p.locator('#alta-otra').click();
  ok(await alta.isVisible() && await alta.evaluate(e => e.index) === 0 && await alta.locator('#alta-nombre').inputValue() === '' && await alta.locator('#alta-invitados .tsl-chip').count() === 0, '«Crear otro» deja el asistente como nuevo');

  // ---- Panel de control ----
  await show('pattern-dashboard');
  const dash = p.locator('#pattern-dashboard .tsl-dashboard');
  ok(await p.locator('#dash-sidebar').evaluate(e => !e.mobile && e.getBoundingClientRect().width > 150), 'la barra lateral se ve completa (no como cajón)');
  ok(await p.locator('#dash-kpis .tsl-stat').count() === 4 && await p.locator('#dash-kpis tsl-sparkline svg').count() === 4, 'cuatro métricas con su minigráfico');
  const labels = () => p.locator('#dash-revenue').evaluate(e => e.data.labels.length);
  const total30 = await p.locator('#dash-total').textContent();
  ok(await labels() === 10 && (await p.locator('#dash-channels').evaluate(e => e.data.segments.length)) === 4, 'gráfica de ingresos (dos series) y dona de canales');
  await p.locator('#dash-range .tsl-segmented__item[value="7d"]').click();
  ok(await labels() === 7 && (await p.locator('#dash-range-desc').textContent()).includes('7 días') && await p.locator('#dash-total').textContent() !== total30, 'el periodo recalcula descripción, métricas y gráficas');
  await p.locator('#dash-range .tsl-segmented__item[value="12m"]').click();
  ok(await labels() === 12, '12 meses: una etiqueta por mes');
  await p.locator('#dash-search').fill('wonka');
  const filtered = await p.locator('#dash-orders').evaluate(e => e.rows.length);
  ok(filtered > 0 && filtered < 24 && (await p.locator('#dash-orders-count').textContent()) === `${filtered} pedidos` && await p.locator('#dash-orders').evaluate(e => e.rows.every(r => r.cliente === 'Wonka')), `la búsqueda de la barra superior filtra la tabla (${filtered})`);
  await p.locator('#dash-search').fill('');
  const cols = () => p.locator('#dash-kpis').evaluate(e => getComputedStyle(e).gridTemplateColumns.split(' ').length);
  const charts = () => p.locator('#pattern-dashboard .tsl-dashboard__charts').evaluate(e => getComputedStyle(e).gridTemplateColumns.split(' ').length);
  const now = await cols();
  await dash.evaluate(e => (e.style.width = '1300px'));
  await p.waitForTimeout(200);
  const wide = await cols(), wideCharts = await charts();
  await dash.evaluate(e => (e.style.width = '100%'));
  ok(now === 2 && wide === 4 && wideCharts === 2, `las métricas siguen el ancho del panel, no el de la ventana (${now} → ${wide} columnas)`);

  // ---- Autenticación ----
  await show('pattern-auth');
  const auth = p.locator('#auth');
  const view = () => auth.evaluate(e => [...e.querySelectorAll('.tsl-auth__view')].filter(v => !v.hidden).map(v => v.dataset.view).join());
  ok(await view() === 'entrar' && await auth.locator('.tsl-auth__aside').isVisible(), 'empieza en «Inicia sesión» con la presentación al lado');
  await auth.locator('[data-view=entrar] [type=submit]').click();
  const err = await auth.locator('#auth-email-err').textContent();
  ok(err.length > 0 && await auth.locator('#auth-email').getAttribute('aria-invalid') === 'true' && await auth.locator('#auth-email').getAttribute('aria-describedby') === 'auth-email-err' && await active() === 'auth-email', `enviar vacío muestra el error junto al campo, enlazado con aria-describedby («${err}»)`);
  await auth.locator('#auth-email').fill('ana@acme.example');
  ok(await auth.locator('#auth-email-err').textContent() === '' && await auth.locator('#auth-email').getAttribute('aria-invalid') === 'false', 'al corregir el campo el error desaparece');
  await auth.locator('#auth-pass').fill('secreto123');
  await auth.locator('[data-view=entrar] [type=submit]').click(); await p.waitForTimeout(150);
  ok((await toasts()).includes('Sesión iniciada'), 'con datos válidos inicia sesión');
  await auth.locator('[data-go=registro]').first().click();
  ok(await view() === 'registro' && await active() === 'Crea tu cuenta', '«Crear cuenta» cambia de vista y enfoca su título');
  await auth.locator('#reg-name').fill('Ana');
  await auth.locator('#reg-email').fill('ana@acme.example');
  await auth.locator('#reg-pass').fill('corta');
  await auth.locator('[data-view=registro] [type=submit]').click();
  ok(await view() === 'registro' && (await auth.locator('#reg-pass-err').textContent()).length > 0 && (await auth.locator('#reg-terms-err').textContent()) === 'Debes aceptarlas para continuar.', 'contraseña corta y condiciones sin aceptar: dos errores');
  await auth.locator('#reg-pass').fill('Contraseña-larga-1');
  await auth.locator('#reg-terms').check();
  await auth.locator('[data-view=registro] [type=submit]').click();
  ok(await view() === 'verificar' && await auth.locator('[data-email]').textContent() === 'ana@acme.example' && await auth.locator('#auth-resend').isDisabled() && (await auth.locator('#auth-resend').textContent()).startsWith('Reenviar en'), 'tras registrarse pide el código, muestra el correo y cuenta atrás para reenviar');
  const cells = auth.locator('#auth-otp input:not([type=hidden])');
  await cells.first().click();
  await p.keyboard.type('000000'); await p.waitForTimeout(100);
  ok(await view() === 'verificar' && (await auth.locator('#auth-otp-err').textContent()).includes('no es correcto'), 'un código incorrecto se rechaza con un aviso');
  await auth.locator('#auth-otp').evaluate(e => e.clear());
  await cells.first().click();
  await p.keyboard.type('482913'); await p.waitForTimeout(100);
  ok(await view() === 'listo' && await auth.locator('[data-done-title]').textContent() === 'Correo verificado', 'al completar un código válido la cuenta queda verificada');
  await auth.locator('[data-view=listo] [data-go=entrar]').click();
  await auth.locator('[data-go=recuperar]').click();
  await auth.locator('#rec-email').fill('ana@acme.example');
  await auth.locator('[data-view=recuperar] [type=submit]').click();
  ok(await view() === 'listo' && (await auth.locator('[data-done-desc]').textContent()).includes('ana@acme.example'), 'recuperar la contraseña confirma el envío del enlace');
  await auth.evaluate(e => (e.style.width = '520px')); await p.waitForTimeout(150);
  ok(await auth.locator('.tsl-auth__aside').isHidden(), 'en un contenedor estrecho la presentación se oculta');
  await auth.evaluate(e => (e.style.width = ''));

  // ---- Ajustes ----
  await show('pattern-settings');
  const set = p.locator('#settings');
  const panel = () => set.evaluate(e => [...e.querySelectorAll('.tsl-settings__panel')].filter(x => !x.hidden).map(x => x.id).join());
  const hash = await p.evaluate(() => location.hash);
  await set.locator('.tsl-nav__item', { hasText: 'Seguridad' }).click();
  ok(await panel() === 'ajustes-seguridad' && await set.locator('.tsl-nav__item[aria-current=page]').textContent() === 'Seguridad' && await active() === 'ajustes-seguridad-t' && await p.evaluate(() => location.hash) === hash, 'la navegación cambia de sección, marca aria-current y enfoca el título sin tocar la URL');
  const barra = set.locator('.tsl-savebar');
  ok(await barra.isHidden(), 'sin cambios no hay barra de guardar');
  await set.locator('#set-2fa').check({ force: true });
  ok(await barra.isVisible() && await set.locator('#set-2fa-alert').isHidden(), 'activar la verificación en dos pasos oculta el aviso y muestra «Guardar»');
  await set.locator('[data-close-session]').first().click();
  ok(await set.locator('#set-sessions li').count() === 2, 'cerrar una sesión la quita de la lista');
  await set.locator('.tsl-nav__item', { hasText: 'Perfil' }).click();
  await set.locator('#set-name').fill('Otro nombre');
  await barra.locator('[type=reset]').click(); await p.waitForTimeout(100);
  ok(await barra.isHidden() && await set.locator('#set-name').inputValue() === 'Luis Islas' && await set.locator('#set-2fa-alert').evaluate(e => !e.hidden), '«Descartar» restablece el formulario y oculta la barra');
  await set.locator('#set-name').fill('Luis I.');
  await barra.locator('[type=submit]').click(); await p.waitForTimeout(150);
  ok(await barra.isHidden() && (await toasts()).includes('Cambios guardados'), '«Guardar cambios» confirma y oculta la barra');
  await set.locator('.tsl-nav__item', { hasText: 'Cuenta' }).click();
  await set.locator('#set-delete').click(); await p.waitForTimeout(250);
  const dlg = p.locator('dialog[open]');
  ok(await dlg.count() === 1 && (await dlg.textContent()).includes('¿Eliminar tu cuenta?'), 'eliminar la cuenta pide confirmación');
  await p.keyboard.press('Escape'); await p.waitForTimeout(200);
  await set.evaluate(e => (e.style.width = '480px')); await p.waitForTimeout(150);
  const narrow = await set.evaluate(e => ({ nav: getComputedStyle(e.querySelector('.tsl-nav')).flexDirection, row: getComputedStyle(e.querySelector('.tsl-settings__panel:not([hidden]) .tsl-settings__row')).gridTemplateColumns.split(' ').length, over: e.scrollWidth - e.clientWidth }));
  ok(narrow.nav === 'row' && narrow.row === 1 && narrow.over <= 1, `en un contenedor estrecho la navegación va en fila y las filas se apilan (${JSON.stringify(narrow)})`);
  await set.evaluate(e => (e.style.width = ''));

  ok(errs.length === 0, 'sin errores de JavaScript' + (errs.length ? `: ${errs.join(' | ')}` : ''));
  await b.close();
  console.log(fails ? `\n${fails} FALLOS` : '\nTODO OK');
  process.exit(fails ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
